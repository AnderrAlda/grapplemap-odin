#!/usr/bin/env python3
"""Literal-bit reference for test_orient_canonically_literal_bits in src/core/reorient_test.odin (#168).

Writes tests/fixtures/canonical.txt: one fixed, asymmetric position and the f64 bit patterns of
`orient_canonically_without_mirror` and `orient_canonically_with_mirror` of it, computed outside Odin.
Python `float` is IEEE binary64, round-to-nearest, no FMA, so every `+ - * /` below is the original's. The three
transcendental functions come from the correctly rounded references of tools/cr_trig_ref.py (sin, cos) and
tools/cr_atan2_ref.py (atan2): the same functions `core` ports (ADR 0003, amendment #161), obtained independently
(`decimal`, not a port). The operation order mirrors src/core/reorient.odin one to one (comments cite the procedures);
a mismatch with the Odin result is investigated, never fixed by editing the fixture.

Usage: python3 tools/canonical_ref.py > tests/fixtures/canonical.txt
Line format: `<player> <joint> <in x y z> <without_mirror x y z> <with_mirror x y z>`, each as 16 hex digits of the f64.
"""

import functools
import math
import random
import struct
import sys

import cr_atan2_ref
import cr_trig_ref

PLAYERS, JOINTS = 2, 23
CORE, HEAD = 20, 22  # Joint.Core, Joint.Head


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def grid(q):
    """q/1000 - 2: a decimal with three digits, rounded once to f64 (the Odin test reads these bits back)."""
    return q / 1000 - 2


def make_position(seed):
    """Asymmetric position of 2 x 23 joints on the 1/1000 grid, no coordinate pattern, one joint at (-0, -0, -0)."""
    rng = random.Random(seed)
    p = [[tuple(grid(rng.randrange(4000)) for _ in range(3)) for _ in range(JOINTS)] for _ in range(PLAYERS)]
    p[0][0] = (-0.0, -0.0, -0.0)  # signed zeros through rotate/mirror (the offset of apply masks a dropped `+ 0`)
    return p


def mirror_joint(j):  # types_test.odin test_mirror_joint: 2k <-> 2k+1 for the 20 limb joints, the rest fixed
    return j ^ 1 if j < 20 else j


@functools.lru_cache(maxsize=None)
def sin_cos(a):
    return cr_trig_ref.sin_cos(a)


def rotate_v3(a, v):  # reorient.odin rotate_v3: matrix entries literal, `0 *` and `+ 0` terms kept
    s, c = sin_cos(a)
    ns = -s
    x, y, z = v
    return (
        ((c * x + 0.0 * y) + s * z) + 0.0,
        ((0.0 * x + 1.0 * y) + 0.0 * z) + 0.0,
        ((ns * x + 0.0 * y) + c * z) + 0.0,
    )


def rotate(a, p):
    return [[rotate_v3(a, v) for v in pl] for pl in p]


def apply(angle, offset, p):  # reorient.odin apply_v3: rotate, then `+ offset` per component
    return [[tuple(r + o for r, o in zip(rotate_v3(angle, v), offset)) for v in pl] for pl in p]


def heading(p):  # transform.odin heading: xz(core1 - core0)
    a, b = p[0][CORE], p[1][CORE]
    return (b[0] - a[0], b[2] - a[2])


def center(p):  # transform.odin center: (a + b) / 2 per component
    a, b = p[0][CORE], p[1][CORE]
    return tuple((u + w) / 2 for u, w in zip(a, b))


def normal_rotation(p):  # reorient.odin normal_rotation: -atan2(h.x, h.z)
    h = heading(p)
    return -cr_atan2_ref.cr_atan2(h[0], h[1])


def normal_translation(p):  # reorient.odin normal_translation: {-c.x, +0, -c.z}
    c = center(p)
    return (-c[0], 0.0, -c[2])


def mirror(p):  # transform.odin mirror: negate x, then permute left/right
    out = [[None] * JOINTS for _ in range(PLAYERS)]
    for pl in range(PLAYERS):
        for j in range(JOINTS):
            v = p[pl][j]
            out[pl][mirror_joint(j)] = (-v[0], v[1], v[2])
    return out


def canonical(p, with_mirror):
    angle = normal_rotation(p)  # canonical_reorientation_without_mirror
    offset = normal_translation(rotate(angle, p))
    q = apply(angle, offset, p)
    if with_mirror and q[1][HEAD][0] >= 0:  # canonical_reorientation_with_mirror: head.x >= 0 (+0 mirrors)
        q = mirror(q)
    return q, angle


def pick_position():
    """The first seed whose mirror test is true and whose angle is not a multiple of pi/4."""
    for seed in range(1, 1000):
        p = make_position(seed)
        q, angle = canonical(p, False)
        if q[1][HEAD][0] >= 0 and abs(math.sin(4 * angle)) > 0.1:
            return seed, p
    sys.exit("no suitable position")


def main():
    seed, p = pick_position()
    without, angle = canonical(p, False)
    with_m, _ = canonical(p, True)
    assert without != with_m
    print(f"# Generated by tools/canonical_ref.py (seed {seed}, angle {angle!r}). pl joint in without_mirror with_mirror.")
    for pl in range(PLAYERS):
        for j in range(JOINTS):
            cols = [p[pl][j], without[pl][j], with_m[pl][j]]
            print(pl, j, *(f"{bits(c):016x}" for v in cols for c in v))


if __name__ == "__main__":
    main()
